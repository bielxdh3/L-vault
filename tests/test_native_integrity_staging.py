import hashlib
import json
import subprocess
import sys
import uuid
from pathlib import Path


REPOSITORY = Path(__file__).resolve().parents[1]
STAGING_ENTRYPOINT = REPOSITORY / "tools" / "build_native_integrity.py"


def _run_git(repo: Path, *args: str) -> str:
    completed = subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def _host_target() -> str:
    completed = subprocess.run(
        ["rustc", "-vV"], check=True, capture_output=True, text=True
    )
    return next(line.removeprefix("host: ") for line in completed.stdout.splitlines() if line.startswith("host: "))


def _synthetic_repo(root: Path, main_source: str = "fn main() {}\n") -> tuple[Path, str, bytes]:
    repo = root / "synthetic-repo"
    package = repo / "native" / "integrity"
    (package / "src").mkdir(parents=True)
    (package / "Cargo.toml").write_text(
        "[package]\nname = \"lvault-integrity\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n",
        encoding="utf-8",
    )
    lockfile = (
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\n"
        "version = 4\n\n"
        "[[package]]\n"
        "name = \"lvault-integrity\"\n"
        "version = \"0.1.0\"\n"
    ).encode()
    (package / "Cargo.lock").write_bytes(lockfile)
    (package / "src" / "main.rs").write_text(main_source, encoding="utf-8")
    (package / ".gitignore").write_text("src/local.rs\n", encoding="utf-8")

    _run_git(repo, "init", "--quiet")
    _run_git(repo, "add", "native/integrity")
    subprocess.run(
        [
            "git",
            "-C",
            str(repo),
            "-c",
            "core.hooksPath=",
            "-c",
            "user.name=Synthetic fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "commit",
            "--quiet",
            "-m",
            "synthetic integrity fixture",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    revision = _run_git(repo, "rev-parse", "HEAD")
    return repo, revision, lockfile


def _run_staging(repo: Path, revision: str, scratch: Path, target: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            sys.executable,
            str(STAGING_ENTRYPOINT),
            "--repo-root",
            str(repo),
            "--source-revision",
            revision,
            "--target",
            target,
            "--scratch-root",
            str(scratch),
        ],
        capture_output=True,
        text=True,
    )


def test_stages_locked_host_binary_and_records_local_provenance(tmp_path: Path) -> None:
    repo, revision, lockfile = _synthetic_repo(tmp_path)
    scratch = tmp_path / "scratch"
    target = _host_target()

    completed = _run_staging(repo, revision, scratch, target)

    assert completed.returncode == 0, completed.stderr
    result = json.loads(completed.stdout)
    manifest_path = Path(result["manifest_path"])
    artifact_path = Path(result["artifact_path"])
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["source_revision"] == revision
    assert manifest["source_tree"] == _run_git(repo, "rev-parse", f"{revision}:native/integrity")
    assert manifest["target"] == target
    assert manifest["platform_format"] == "PE"
    assert artifact_path.suffix == ".exe"
    assert artifact_path.read_bytes()[:2] == b"MZ"
    assert manifest["lockfile_sha256"] == hashlib.sha256(lockfile).hexdigest()
    assert manifest["build_flags"] == ["--locked", "--offline"]
    assert manifest["evidence"] == "unsigned-local-build"
    assert manifest["artifact_sha256"] == hashlib.sha256(artifact_path.read_bytes()).hexdigest()
    assert artifact_path.is_relative_to(scratch.resolve())
    assert manifest_path.is_relative_to(scratch.resolve())
    assert not (repo / "native" / "integrity" / "target").exists()
    assert _run_git(repo, "status", "--porcelain") == ""


def test_rejects_ignored_untracked_crate_source_before_staging(tmp_path: Path) -> None:
    repo, revision, _ = _synthetic_repo(tmp_path, "mod local;\nfn main() { local::run(); }\n")
    package = repo / "native" / "integrity"
    (package / "src" / "local.rs").write_text("pub fn run() {}\n", encoding="utf-8")
    scratch = tmp_path / "scratch"

    completed = _run_staging(repo, revision, scratch, _host_target())

    assert completed.returncode != 0
    assert "differs from the requested source revision" in completed.stderr
    assert not scratch.exists()


def test_rejects_non_e_scratch_before_creating_output(tmp_path: Path) -> None:
    repo, revision, _ = _synthetic_repo(tmp_path)
    outside_scratch = Path(f"C:/lvault-invalid-scratch-{uuid.uuid4().hex}")

    completed = _run_staging(repo, revision, outside_scratch, _host_target())

    assert completed.returncode != 0
    assert "scratch root must be on E:" in completed.stderr
    assert not outside_scratch.exists()


def test_rejects_non_host_target_before_creating_scratch(tmp_path: Path) -> None:
    repo, revision, _ = _synthetic_repo(tmp_path)
    scratch = tmp_path / "scratch"

    completed = _run_staging(repo, revision, scratch, "not-a-target")

    assert completed.returncode != 0
    assert "does not match installed Rust host" in completed.stderr
    assert not scratch.exists()
