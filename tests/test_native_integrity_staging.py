REPOSITORY = Path(__file__).resolve().parents[1]
STAGING_ENTRYPOINT = REPOSITORY / "tools" / "build_native_integrity.py"
_STAGING_SPEC = importlib.util.spec_from_file_location(
    "build_native_integrity", STAGING_ENTRYPOINT
)
assert _STAGING_SPEC is not None and _STAGING_SPEC.loader is not None
build_native_integrity = importlib.util.module_from_spec(_STAGING_SPEC)
_STAGING_SPEC.loader.exec_module(build_native_integrity)


def _classify_synthetic_drive(root: Path, monkeypatch, drive: str) -> None:
    resolved_root = root.resolve()
    original_drive = build_native_integrity._path_drive

    def synthetic_drive(path: Path) -> str:
        if path == resolved_root or path.is_relative_to(resolved_root):
            return drive
        return original_drive(path)

    monkeypatch.setattr(build_native_integrity, "_path_drive", synthetic_drive)


def test_synthetic_drive_classification_does_not_rewrite_child_paths(
    tmp_path: Path, monkeypatch
) -> None:
    filesystem_root = str(tmp_path)

    _classify_synthetic_drive(tmp_path, monkeypatch, "E:")
    child = tmp_path / "synthetic-child"

    assert build_native_integrity._path_drive(child) == "E:"
    assert str(child) == os.path.join(filesystem_root, "synthetic-child")
    assert str(child.resolve()) == os.path.join(filesystem_root, "synthetic-child")


def _run_git(repo: Path, *args: str) -> str:
    completed = subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def _host_target() -> str:
    completed = subprocess.run(
        ["rustc", "-vV"], check=True, capture_output=True, text=True
    )
    return next(line.removeprefix("host: ") for line in completed.stdout.splitlines() if line.startswith("host: "))


def _synthetic_repo(
    root: Path,
    main_source: str = "fn main() {}\n",
    build_script: str | None = None,
) -> tuple[Path, str, bytes]:
    repo = root / "synthetic-repo"
    package = repo / "native" / "integrity"
    (package / "src").mkdir(parents=True)
    (package / "Cargo.toml").write_text(
        "[package]\nname = \"lvault-integrity\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n"
        + ('build = "build.rs"\n' if build_script else ""),
        encoding="utf-8",
    )
    lockfile = (
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\n"
        "version = 4\n\n"
        "[[package]]\n"
        "name = \"lvault-integrity\"\n"
        "version = \"0.1.0\"\n"
    ).encode()
    (package / "Cargo.lock").write_bytes(lockfile)
    (package / "src" / "main.rs").write_text(main_source, encoding="utf-8")
    if build_script:
        (package / "build.rs").write_text(build_script, encoding="utf-8")
    (package / ".gitignore").write_text("src/local.rs\n", encoding="utf-8")

    _run_git(repo, "init", "--quiet")
    _run_git(repo, "add", "native/integrity")
    subprocess.run(
        [
            "git",
            "-C",
            str(repo),
            "-c",
            "core.hooksPath=",
            "-c",
            "user.name=Synthetic fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "commit",
            "--quiet",
            "-m",
            "synthetic integrity fixture",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    revision = _run_git(repo, "rev-parse", "HEAD")
    return repo, revision, lockfile


def _run_staging(
    repo: Path,
    revision: str,
    scratch: Path,
    target: str,
    registry_source: Path | None = None,
) -> subprocess.CompletedProcess[str]:
    command = [
        sys.executable,
        str(STAGING_ENTRYPOINT),
        "--repo-root",
        str(repo),
        "--source-revision",
        revision,
        "--target",
        target,
        "--scratch-root",
        str(scratch),
    ]
    if registry_source is not None:
        command.extend(["--cargo-registry-source", str(registry_source)])
    return subprocess.run(
        command,
        capture_output=True,
        text=True,
    )


def _run_staging_main(
    repo: Path,
    revision: str,
    scratch: Path,
    target: str,
    monkeypatch,
    registry_source: Path | None = None,
) -> int:
    command = [
        str(STAGING_ENTRYPOINT),
        "--repo-root",
        str(repo),
        "--source-revision",
        revision,
        "--target",
        target,
        "--scratch-root",
        str(scratch),
    ]
    if registry_source is not None:
        command.extend(["--cargo-registry-source", str(registry_source)])
    monkeypatch.setattr(sys, "argv", command)
    return build_native_integrity.main()


def test_stages_locked_host_binary_and_records_local_provenance(
    tmp_path: Path, monkeypatch, capsys
) -> None:
    _classify_synthetic_drive(tmp_path, monkeypatch, "E:")
    repo, revision, lockfile = _synthetic_repo(tmp_path)
    scratch = tmp_path / "scratch"
    target = _host_target()

    returncode = _run_staging_main(repo, revision, scratch, target, monkeypatch)
    completed = capsys.readouterr()

    assert returncode == 0, completed.err
    result = json.loads(completed.out)
    manifest_path = Path(result["manifest_path"])
    artifact_path = Path(result["artifact_path"])
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["source_revision"] == revision
    assert manifest["source_tree"] == _run_git(repo, "rev-parse", f"{revision}:native/integrity")
    assert manifest["target"] == target
    assert manifest["platform_format"] == "PE"
    assert artifact_path.suffix == ".exe"
    assert artifact_path.read_bytes()[:2] == b"MZ"
    assert manifest["lockfile_sha256"] == hashlib.sha256(lockfile).hexdigest()
    assert manifest["build_flags"] == ["--locked", "--offline"]
    assert manifest["evidence"] == "unsigned-local-build"
    assert manifest["artifact_sha256"] == hashlib.sha256(artifact_path.read_bytes()).hexdigest()
    assert artifact_path.is_relative_to(scratch.resolve())
    assert manifest_path.is_relative_to(scratch.resolve())
    assert not (repo / "native" / "integrity" / "target").exists()
    assert _run_git(repo, "status", "--porcelain") == ""


